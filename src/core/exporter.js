/*
 * exporter.js – SVG files for the laser cutter.
 *
 * Conventions (work with LightBurn, Inkscape, Glowforge, xTool, ...):
 *   - 1 user unit = 1 mm, width/height carry the "mm" unit, viewBox starts at 0 0
 *   - all transforms are baked into the coordinates (some laser tools ignore transforms)
 *   - every part is a <g>; the inner cuts (slots) come first so they are cut before the
 *     outline frees the part; inner and outer cuts have their own stroke colour so they
 *     can be assigned to layers / cut order by colour
 *   - no fills, hairline strokes (stroke width configurable)
 */
(function () {
  'use strict';
  const PC = (globalThis.PlaneCutter = globalThis.PlaneCutter || {});
  const S = PC.svg;
  const G = PC.geometry;

  const DEFAULT_STYLE = {
    cutColor: '#ff0000',
    innerColor: '#0000ff',
    strokeWidth: 0.1, // mm
    partMargin: 2, // mm around a single exported part
  };

  function pathAttrs(color, style) {
    return { fill: 'none', stroke: color, 'stroke-width': S.num(style.strokeWidth), 'stroke-linejoin': 'round' };
  }

  function partGroup(outline, cutouts, geo, style, id) {
    const children = cutouts.map((c, i) => S.el('path', { id: `${id}-slot-${i + 1}`, class: 'inner-cut', d: S.pathData(c), ...pathAttrs(style.innerColor, style) }));
    children.push(S.el('path', { id: `${id}-outline`, class: 'outer-cut', d: S.pathData(outline), ...pathAttrs(style.cutColor, style) }));
    return S.el('g', { id, 'data-template': geo.templateId, 'data-part': geo.kind, 'data-scale': S.num(geo.scale, 4) }, children.map((c) => `\n    ${c}`)) + '\n';
  }

  function paramsDescription(params) {
    return `material ${params.thickness} mm, slot width ${S.num(params.thickness + params.slotClearance)} mm (clearance ${params.slotClearance} mm), slot length +${params.slotLengthExtra} mm, ${params.slotEnds} ends`;
  }

  /** The whole sheet with every placed part at its position. */
  function sheetSvg(sheet, geometryFor, style = {}) {
    const st = { ...DEFAULT_STYLE, ...style };
    const groups = [];
    let params = null;
    for (const item of sheet.items) {
      const geo = geometryFor(item);
      params = params || geo.params;
      const id = `${geo.templateId}-${geo.kind}-${item.id}`;
      groups.push('  ' + partGroup(PC.sheet.placedOutline(item, geo), PC.sheet.placedCutouts(item, geo), geo, st, id));
    }
    const names = [...new Set(sheet.items.map((it) => PC.parts.getTemplate(it.templateId).name))].join(', ');
    return S.document({
      width: sheet.width,
      height: sheet.height,
      title: `Plane Cutter sheet ${sheet.width} × ${sheet.height} mm`,
      desc: `${sheet.items.length} parts (${names || 'none'}). ${params ? paramsDescription(params) : ''} Generated by Plane Cutter.`,
      body: groups.join(''),
    });
  }

  /** One part on its own, in its natural orientation, with a small margin. */
  function partSvg(geo, style = {}) {
    const st = { ...DEFAULT_STYLE, ...style };
    const m = st.partMargin;
    const b = geo.bbox;
    const shift = { x: -b.minX + m, y: -b.minY + m };
    const outline = G.transformPoints(geo.outline, shift);
    const cutouts = geo.cutouts.map((c) => G.transformPoints(c, shift));
    return S.document({
      width: b.width + 2 * m,
      height: b.height + 2 * m,
      title: geo.name,
      desc: `${geo.name} at ${Math.round(geo.scale * 100)} % (${b.width.toFixed(1)} × ${b.height.toFixed(1)} mm). ${paramsDescription(geo.params)}. Generated by Plane Cutter.`,
      body: '  ' + partGroup(outline, cutouts, geo, st, `${geo.templateId}-${geo.kind}`),
    });
  }

  function slug(s) {
    return String(s)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
  }

  /**
   * e.g. camo-fuselage-100pct-3mm.svg.  A fuselage made for another plane's wing or tail
   * says so: camo-fuselage-fits-racer-wing-100pct-3mm.svg
   */
  function partFilename(geo) {
    const foreign = geo.fits ? ['wing', 'tail'].filter((kind) => geo.fits[kind].templateId !== geo.templateId) : [];
    const fits = foreign.length ? `-fits-${foreign.map((kind) => `${slug(geo.fits[kind].templateId)}-${kind}`).join('-')}` : '';
    return `${slug(geo.templateId)}-${geo.kind}${fits}-${Math.round(geo.scale * 100)}pct-${String(geo.params.thickness).replace('.', 'p')}mm.svg`;
  }

  function sheetFilename(sheet) {
    return `plane-cutter-sheet-${sheet.width}x${sheet.height}mm.svg`;
  }

  PC.exporter = { DEFAULT_STYLE, sheetSvg, partSvg, partFilename, sheetFilename, slug };
})();
